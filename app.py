"""Streamlit brain MRI tumor segmentation using the trained custom U-Net.

Run: streamlit run app.py
Expected weights: best.pth generated by the matching training notebook.
"""

from pathlib import Path

import cv2
import numpy as np
import streamlit as st
import torch
from torch import nn


IMG_SIZE = 256
MODEL_PATH = Path(__file__).resolve().parent / "best.pth"
MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
STD = np.array([0.229, 0.224, 0.225], dtype=np.float32)


# The architecture must match the *custom U-Net* used to generate best.pth.
class ConvBlock(nn.Module):
    def __init__(self, in_channels: int, out_channels: int):
        super().__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, kernel_size=3, padding=1),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(),
            nn.Conv2d(out_channels, out_channels, kernel_size=3, padding=1),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.conv(x)


class UNet(nn.Module):
    def __init__(self, in_channels: int = 3, out_channels: int = 2, init_features: int = 16):
        super().__init__()
        self.encoder1 = ConvBlock(in_channels, init_features)
        self.pool1 = nn.MaxPool2d(2)
        self.encoder2 = ConvBlock(init_features, init_features * 2)
        self.pool2 = nn.MaxPool2d(2)
        self.encoder3 = ConvBlock(init_features * 2, init_features * 4)
        self.pool3 = nn.MaxPool2d(2)
        self.encoder4 = ConvBlock(init_features * 4, init_features * 8)
        self.pool4 = nn.MaxPool2d(2)
        self.encoder5 = ConvBlock(init_features * 8, init_features * 16)

        self.upconv4 = nn.ConvTranspose2d(init_features * 16, init_features * 8, kernel_size=2, stride=2)
        self.decoder4 = ConvBlock(init_features * 16, init_features * 8)
        self.upconv3 = nn.ConvTranspose2d(init_features * 8, init_features * 4, kernel_size=2, stride=2)
        self.decoder3 = ConvBlock(init_features * 8, init_features * 4)
        self.upconv2 = nn.ConvTranspose2d(init_features * 4, init_features * 2, kernel_size=2, stride=2)
        self.decoder2 = ConvBlock(init_features * 4, init_features * 2)
        self.upconv1 = nn.ConvTranspose2d(init_features * 2, init_features, kernel_size=2, stride=2)
        self.decoder1 = ConvBlock(init_features * 2, init_features)
        self.output = nn.Conv2d(init_features, out_channels, kernel_size=1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        enc1 = self.encoder1(x)
        enc2 = self.encoder2(self.pool1(enc1))
        enc3 = self.encoder3(self.pool2(enc2))
        enc4 = self.encoder4(self.pool3(enc3))
        bottleneck = self.encoder5(self.pool4(enc4))
        x = self.decoder4(torch.cat((self.upconv4(bottleneck), enc4), dim=1))
        x = self.decoder3(torch.cat((self.upconv3(x), enc3), dim=1))
        x = self.decoder2(torch.cat((self.upconv2(x), enc2), dim=1))
        x = self.decoder1(torch.cat((self.upconv1(x), enc1), dim=1))
        return self.output(x)


@st.cache_resource

def load_model():
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = UNet(in_channels=3, out_channels=2, init_features=16)
    # Only load weights files from sources you trust.
    state_dict = torch.load(MODEL_PATH, map_location="cpu", weights_only=True)
    model.load_state_dict(state_dict, strict=True)
    model.to(device)
    model.eval()
    return model, device


def preprocess_image(rgb_image: np.ndarray) -> torch.Tensor:
    """Match training: RGB -> resize -> /255 -> ImageNet normalize -> CHW."""
    resized = cv2.resize(rgb_image, (IMG_SIZE, IMG_SIZE), interpolation=cv2.INTER_LINEAR)
    image = resized.astype(np.float32) / 255.0
    image = (image - MEAN) / STD
    image = np.ascontiguousarray(image.transpose(2, 0, 1))
    return torch.from_numpy(image).unsqueeze(0)


def make_overlay(rgb_image: np.ndarray, tumor_mask: np.ndarray, alpha: float = 0.4) -> np.ndarray:
    overlay = rgb_image.copy()
    red = np.zeros_like(overlay)
    red[:, :, 0] = 255  # RGB red
    blended = cv2.addWeighted(overlay, 1.0 - alpha, red, alpha, 0)
    overlay[tumor_mask == 1] = blended[tumor_mask == 1]
    return overlay


st.set_page_config(page_title="腦部 MRI 腫瘤分割", page_icon="🧠", layout="wide")
st.title("🧠 腦部 MRI 腫瘤分割（U-Net）")
st.write("上傳一張與模型訓練資料格式相符的腦部 MRI 影像，查看模型預測的腫瘤區域。")
st.caption("此工具僅供 AI 模型研究與教學，不可作為醫療診斷依據。")

try:
    model, device = load_model()
except FileNotFoundError:
    st.error(f"找不到模型權重：{MODEL_PATH.name}。請將訓練完成的 best.pth 放在 app.py 同一資料夾。")
    st.stop()
except (RuntimeError, ValueError, TypeError) as exc:
    st.error("模型權重載入失敗。請確認 best.pth 是由同一個自訂 U-Net（init_features=16）儲存的 state_dict。")
    st.code(str(exc))
    st.stop()

st.caption(f"推論裝置：{str(device).upper()} ｜ 模型輸入：RGB、{IMG_SIZE}×{IMG_SIZE} ｜ 輸出：背景 / 腫瘤")
uploaded_file = st.file_uploader("選擇腦部 MRI 影像", type=["tif", "tiff", "png", "jpg", "jpeg"])

if uploaded_file is not None:
    file_bytes = np.frombuffer(uploaded_file.getvalue(), dtype=np.uint8)
    bgr_image = cv2.imdecode(file_bytes, cv2.IMREAD_COLOR)
    if bgr_image is None:
        st.error("無法讀取圖片。請上傳有效的 8-bit、3 通道影像。")
        st.stop()

    rgb_image = cv2.cvtColor(bgr_image, cv2.COLOR_BGR2RGB)
    st.image(rgb_image, caption="原始 MRI 影像", width="stretch")

    if st.button("開始腫瘤分割", type="primary"):
        x = preprocess_image(rgb_image).to(device)
        with torch.inference_mode():
            logits = model(x)                       # (1, 2, 256, 256)
            probs = torch.softmax(logits, dim=1)
            mask_256 = probs.argmax(dim=1)[0].cpu().numpy().astype(np.uint8)

        original_h, original_w = rgb_image.shape[:2]
        # Nearest-neighbor interpolation preserves binary class IDs.
        tumor_mask = cv2.resize(mask_256, (original_w, original_h), interpolation=cv2.INTER_NEAREST)
        overlay = make_overlay(rgb_image, tumor_mask)
        mask_display = np.zeros_like(rgb_image)
        mask_display[tumor_mask == 1] = [255, 0, 0]  # RGB red

        col1, col2, col3 = st.columns(3)
        with col1:
            st.image(rgb_image, caption="原始 MRI", width="stretch")
        with col2:
            st.image(mask_display, caption="預測腫瘤遮罩（紅色）", width="stretch")
        with col3:
            st.image(overlay, caption="原圖 + 腫瘤遮罩", width="stretch")

        tumor_pixels = int(np.count_nonzero(mask_256))
        tumor_ratio = 100.0 * tumor_pixels / mask_256.size
        st.write(f"預測腫瘤像素占比（在 {IMG_SIZE}×{IMG_SIZE} 輸出網格）：**{tumor_ratio:.2f}%**")
        st.caption("像素占比不是腫瘤體積或病情指標；模型分類結果需要使用標註資料另行驗證。")
        success, encoded = cv2.imencode(".png", cv2.cvtColor(overlay, cv2.COLOR_RGB2BGR))
        if success:
            st.download_button("下載疊加結果（PNG）", encoded.tobytes(), file_name="tumor_overlay.png", mime="image/png")
